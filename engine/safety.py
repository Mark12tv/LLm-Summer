"""Жёсткие рамки контента — часть формата, а не настройка.

Правила из `reality.md` §23:
* все персонажи — совершеннолетние;
* внутри лагеря для Ульяны любые сексуальные сцены запрещены;
* после лагеря персонажи взрослеют — это отдельный эпилог, отдельная ветка,
  и он не отменяет запрет внутри смены.

Здесь только декларация рамок: проверка текста делается в валидаторе
выходов (этап 3) и постфильтре перед показом игроку.
"""

from __future__ import annotations

from typing import Literal

Phase = Literal["camp", "epilogue"]

SAFETY_PREAMBLE = (
    "Все персонажи совершеннолетние (18+). "
    "Запрещено: сексуальный контент, насилие, унижение, любая эротика. "
    "Ты пишешь бытовую драму в пионерлагере 1985 года."
)

# Внутри лагеря — полный запрет; в эпилоге рамки те же, но персонажи взрослые.
IN_CAMP_BLOCKED = frozenset({"ulyana"})


def sexual_content_allowed(agent_id: str, phase: Phase) -> bool:
    """Сексуальный контент выключен для всех, всегда.

    Функция существует, чтобы правило было явным и тестируемым:
    смена фазы не открывает запрет, а лишь снимает особую пометку Ульяны
    (в эпилоге она взрослая, но контент всё равно вне рамок проекта).
    """
    return False


def needs_extra_guard(agent_id: str, phase: Phase) -> bool:
    """Нужен ли усиленный постфильтр по конкретному агенту."""
    return phase == "camp" and agent_id in IN_CAMP_BLOCKED
